"""Additive local conservation laws of generalised Langton's ants, for all moduli at once.

A law is  V = a*x + b*y + e*t + Phi(h, s(pos)) + sum_cells w(s(cell), colour)  (mod m),
with w(s, 0) = 0 so a blank field contributes nothing.  V is a *proved* invariant when every
local transition the family admits leaves it unchanged: the ant on a cell of colour c and class s
with heading h turns by the rule's turn for c, the cell goes c -> (c+1) % n, the ant steps.  Each
such condition is an integer-linear equation in the unknowns, so the laws mod m are the kernel of
one integer matrix M reduced mod m.  One Smith normal form U M V = D over Z gives the kernel at
every m: it is Z_m^(k-r) x prod_i Z_{gcd(d_i, m)}, generated by the columns of V.

Families (see experiments/2026-10-22-invariant-mining-snf/README.md):
  A0  no class, Phi = d*h with integer h (the ansatz of src/invariants.rs)
  F1  no class, Phi arbitrary on h
  F2  class (x+y) mod 2, only states with h = s (mod 2), Phi arbitrary on those
  F3  class (x mod 2, y mod 2), only states with h = x+y (mod 2)

Standard library only.  Usage:
  uv run --frozen experiments/_lib/lawmod.py RULE [RULE ...] [--family F1] [--moduli 2,4]
  uv run --frozen experiments/_lib/lawmod.py --selftest
"""
from __future__ import annotations

import argparse
import itertools
import math
import random
import sys
from dataclasses import dataclass

DIRS = [(0, -1), (1, 0), (0, 1), (-1, 0)]  # north is -y, as src/lib.rs
FAMILIES = ("A0", "F1", "F2", "F3")


def deltas(rule: str) -> list[int]:
    """Quarter turns clockwise per colour: R = 1, L = 3."""
    return [{"R": 1, "L": 3}[ch] for ch in rule.upper()]


@dataclass(frozen=True)
class Family:
    name: str

    def classes(self) -> list[int]:
        return {"A0": [0], "F1": [0], "F2": [0, 1], "F3": [0, 1, 2, 3]}[self.name]

    def step_class(self, s: int, dx: int, dy: int) -> int:
        if self.name in ("A0", "F1"):
            return 0
        if self.name == "F2":
            return (s + dx + dy) % 2
        return (((s >> 1) + dx) % 2) * 2 + ((s & 1) + dy) % 2

    def reachable(self) -> list[tuple[int, int]]:
        """(heading, class) pairs the ant can be in; the manifold h + x + y even for F2/F3."""
        if self.name in ("A0", "F1"):
            return [(h, 0) for h in range(4)]
        par = (lambda s: s) if self.name == "F2" else (lambda s: (s >> 1) + (s & 1))
        return [(h, s) for s in self.classes() for h in range(4) if (h - par(s)) % 2 == 0]

    def phi_keys(self) -> list[tuple[int, int]]:
        """Unknown Phi values: all reachable pairs but the first (gauge). A0 has the single slope d."""
        return [] if self.name == "A0" else self.reachable()[1:]


@dataclass(frozen=True)
class Layout:
    """Column order of the unknown vector: a, b, e, Phi..., then w(s, c) for c = 1..n-1."""

    family: Family
    n: int

    def names(self) -> list[str]:
        out = ["a", "b", "e"]
        out += ["d"] if self.family.name == "A0" else [f"phi{k}" for k in self.family.phi_keys()]
        out += [f"w{s}_{c}" for s in self.family.classes() for c in range(1, self.n)]
        return out

    def size(self) -> int:
        return len(self.names())


def transition_rows(fam: Family, n: int, allowed: list[list[int]]) -> list[list[int]]:
    """Distinct integer rows; allowed[c] lists the turns (1 or 3) colour c may take."""
    lay = Layout(fam, n)
    names = lay.names()
    col = {nm: i for i, nm in enumerate(names)}
    phi_col = {k: col[f"phi{k}"] for k in fam.phi_keys()} if fam.name != "A0" else {}
    rows: set[tuple[int, ...]] = set()
    for c in range(n):
        for turn in allowed[c]:
            for h, s in fam.reachable():
                h2 = (h + turn) % 4
                dx, dy = DIRS[h2]
                s2 = fam.step_class(s, dx, dy)
                r = [0] * len(names)
                r[col["a"]] += dx
                r[col["b"]] += dy
                r[col["e"]] += 1
                if fam.name == "A0":
                    r[col["d"]] += h2 - h
                else:
                    if (h2, s2) in phi_col:
                        r[phi_col[(h2, s2)]] += 1
                    if (h, s) in phi_col:
                        r[phi_col[(h, s)]] -= 1
                if (c + 1) % n != 0:
                    r[col[f"w{s}_{c + 1}"]] += 1
                if c != 0:
                    r[col[f"w{s}_{c}"]] -= 1
                rows.add(tuple(r))
    return [list(r) for r in sorted(rows)]


def rule_rows(fam: Family, rule: str) -> list[list[int]]:
    return transition_rows(fam, len(rule), [[d] for d in deltas(rule)])


def universal_rows(fam: Family, n: int) -> list[list[int]]:
    return transition_rows(fam, n, [[1, 3]] * n)


@dataclass
class Snf:
    """U M V = D with V unimodular (columns tracked); `diag` are the raw diagonal entries."""

    k: int
    V: list[list[int]]
    diag: list[int]  # length r, all positive

    @property
    def rank(self) -> int:
        return len(self.diag)

    def canonical(self) -> tuple[int, ...]:
        """Invariant factors d_1 | d_2 | ... including 1s."""
        d = list(self.diag)
        changed = True
        while changed:
            changed = False
            for i in range(len(d)):
                for j in range(i + 1, len(d)):
                    g = math.gcd(d[i], d[j])
                    lo, hi = g, d[i] * d[j] // g
                    if (lo, hi) != (d[i], d[j]):
                        d[i], d[j] = lo, hi
                        changed = True
        return tuple(sorted(d))

    def fingerprint(self) -> tuple[int, tuple[int, ...]]:
        """(free rank, nontrivial invariant factors): determines the law group at every modulus."""
        return (self.k - self.rank, tuple(x for x in self.canonical() if x > 1))

    def order(self, m: int) -> int:
        free, facs = self.fingerprint()
        return m**free * math.prod(math.gcd(f, m) for f in facs)

    def generators(self, m: int) -> list[list[int]]:
        gens = []
        for i, d in enumerate(self.diag):
            g = math.gcd(d, m)
            if g == 1:
                continue
            scale = m // g
            gens.append([(scale * self.V[r][i]) % m for r in range(self.k)])
        for i in range(self.rank, self.k):
            gens.append([self.V[r][i] % m for r in range(self.k)])
        return gens


def snf(M: list[list[int]], k: int) -> Snf:
    A = [list(r) for r in M]
    R = len(A)
    V = [[int(i == j) for j in range(k)] for i in range(k)]
    diag: list[int] = []

    def swap_cols(i: int, j: int) -> None:
        for row in A:
            row[i], row[j] = row[j], row[i]
        for row in V:
            row[i], row[j] = row[j], row[i]

    i = 0
    while i < min(R, k):
        best = None
        for r in range(i, R):
            for c in range(i, k):
                v = abs(A[r][c])
                if v and (best is None or v < best[0]):
                    best = (v, r, c)
        if best is None:
            break
        _, pr, pc = best
        A[i], A[pr] = A[pr], A[i]
        if pc != i:
            swap_cols(i, pc)
        while True:
            dirty = False
            for r in range(i + 1, R):
                if A[r][i]:
                    q = A[r][i] // A[i][i]
                    if q:
                        A[r] = [x - q * y for x, y in zip(A[r], A[i])]
                    if A[r][i]:
                        A[i], A[r] = A[r], A[i]
                        dirty = True
            for c in range(i + 1, k):
                if A[i][c]:
                    q = A[i][c] // A[i][i]
                    if q:
                        for row in A:
                            row[c] -= q * row[i]
                        for row in V:
                            row[c] -= q * row[i]
                    if A[i][c]:
                        swap_cols(i, c)
                        dirty = True
            if not dirty:
                break
        diag.append(abs(A[i][i]))
        i += 1
    return Snf(k, V, diag)


# ---------------------------------------------------------------- law objects and rendering


def unpack(fam: Family, n: int, vec: list[int], m: int) -> dict:
    """Vector -> a readable law with all keys present (gauge entries are 0)."""
    names = Layout(fam, n).names()
    val = dict(zip(names, vec))
    law = {"m": m, "a": val["a"], "b": val["b"], "e": val["e"], "d": val.get("d", 0), "phi": {}, "w": {}}
    if fam.name != "A0":
        reach = fam.reachable()
        law["phi"] = {reach[0]: 0, **{k: val[f"phi{k}"] for k in reach[1:]}}
    for s in fam.classes():
        law["w"][s] = [0] + [val[f"w{s}_{c}"] for c in range(1, n)]
    return law


def render(law: dict, fam: Family) -> str:
    m = law["m"]
    parts = []
    for coef, sym in ((law["a"], "x"), (law["b"], "y"), (law["e"], "t")):
        if coef % m:
            parts.append(f"{coef}*{sym}")
    if law["d"] % m:
        parts.append(f"{law['d']}*h")
    if any(v % m for v in law["phi"].values()):
        parts.append("Phi" + str({k: v for k, v in law["phi"].items()}))
    for s, ws in law["w"].items():
        if any(v % m for v in ws):
            tag = "" if fam.name in ("A0", "F1") else f"[s={s}]"
            parts.append(f"sum w{tag}" + str(ws))
    return (" + ".join(parts) if parts else "0") + f"  (mod {m})"


def check_vector(fam: Family, M: list[list[int]], vec: list[int], m: int) -> bool:
    return all(sum(a * b for a, b in zip(row, vec)) % m == 0 for row in M)


# ---------------------------------------------------------------- selftest


def selftest() -> None:
    rng = random.Random(20261022)
    # 1. SNF kernel formula versus brute force on random small integer matrices.
    for _ in range(100):
        R, k = rng.randint(1, 5), rng.randint(1, 4)
        M = [[rng.randint(-6, 6) for _ in range(k)] for _ in range(R)]
        sn = snf(M, k)
        for m in (2, 3, 4, 6, 8, 12):
            brute = sum(1 for u in itertools.product(range(m), repeat=k) if check_vector(None, M, list(u), m))
            assert brute == sn.order(m), (M, m, brute, sn.order(m))
            for g in sn.generators(m):
                assert check_vector(None, M, g, m)
    # 2. Gauge-fixed families on tiny rules versus brute force; F1 contains A0, F2 contains F1.
    for rule in ("RL", "RR", "RLR"):
        n = len(rule)
        for name, ms in (("A0", (2, 3, 4)), ("F1", (2, 3)), ("F2", (2,)), ("F3", (2,))):
            fam = Family(name)
            M = rule_rows(fam, rule)
            k = Layout(fam, n).size()
            sn = snf(M, k)
            for m in ms:
                brute = sum(1 for u in itertools.product(range(m), repeat=k) if check_vector(fam, M, list(u), m))
                assert brute == sn.order(m), (rule, name, m, brute, sn.order(m))
    # 3. Langton's heading law: A0 on RL has d=1, w_1=-1 (mod 4), i.e. heading = #colour-1 cells.
    fam = Family("A0")
    M = rule_rows(fam, "RL")
    names = Layout(fam, 2).names()
    vec = [0, 0, 0, 1, 3]  # a,b,e,d,w0_1
    assert names == ["a", "b", "e", "d", "w0_1"] and check_vector(fam, M, vec, 4)
    print("lawmod selftest: ok")


# ---------------------------------------------------------------- CLI


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("rules", nargs="*")
    ap.add_argument("--family", default="F1", choices=FAMILIES)
    ap.add_argument("--moduli", default="2,4")
    ap.add_argument("--selftest", action="store_true")
    args = ap.parse_args()
    if args.selftest:
        selftest()
        return
    if not args.rules:
        ap.error("give at least one RULE or --selftest")
    fam = Family(args.family)
    for rule in args.rules:
        n = len(rule)
        sn = snf(rule_rows(fam, rule), Layout(fam, n).size())
        un = snf(universal_rows(fam, n), Layout(fam, n).size())
        free, facs = sn.fingerprint()
        print(f"{rule} {fam.name}: free={free} factors={list(facs)}  universal: free={un.fingerprint()[0]} factors={list(un.fingerprint()[1])}")
        for m in (int(x) for x in args.moduli.split(",")):
            print(f"  m={m}: |G|={sn.order(m)} |U|={un.order(m)} extra index={sn.order(m) // un.order(m)}")
            for g in sn.generators(m):
                print("    " + render(unpack(fam, n, g, m), fam))


if __name__ == "__main__":
    sys.exit(main())
